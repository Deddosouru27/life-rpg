// ════════════════════════════════════════════════════════════════
// Выбор реплики
// ════════════════════════════════════════════════════════════════

export interface LineContext {
  rank: Rank;
  streak: number;
  hpStage: HpStage;
}

function matches(line: MerchantLine, ctx: LineContext): boolean {
  if (line.ranks && !line.ranks.includes(ctx.rank)) return false;
  if (line.minStreak !== undefined && ctx.streak < line.minStreak) return false;
  if (line.maxStreak !== undefined && ctx.streak > line.maxStreak) return false;
  if (line.hpStages && !line.hpStages.includes(ctx.hpStage)) return false;
  return true;
}

/**
 * Подбирает реплику под контекст. Более специфичные реплики (с большим числом
 * условий) предпочитаются общим — иначе торговец всегда говорил бы дежурные фразы.
 */
export function pickLine(
  merchant: Merchant,
  key: MerchantLineKey,
  ctx: LineContext,
  roll: number,
): string {
  const pool = merchant.lines[key].filter((l) => matches(l, ctx));
  if (pool.length === 0) {
    const fallback = merchant.lines[key][0];
    return fallback?.text ?? '…';
  }

  const specificity = (l: MerchantLine): number =>
    (l.ranks ? 1 : 0) +
    (l.minStreak !== undefined ? 1 : 0) +
    (l.maxStreak !== undefined ? 1 : 0) +
    (l.hpStages ? 1 : 0);

  const maxSpec = Math.max(...pool.map(specificity));
  const best = pool.filter((l) => specificity(l) === maxSpec);
  const index = Math.floor(Math.abs(roll) * best.length) % best.length;
  return best[index]?.text ?? '…';
}

/** Реплика приветствия с учётом состояния здоровья: раненого встречают иначе. */
export function pickGreeting(merchant: Merchant, ctx: LineContext, roll: number): string {
  if (ctx.hpStage === 'exhausted') return pickLine(merchant, 'exhausted', ctx, roll);
  if (ctx.hpStage === 'wounded') return pickLine(merchant, 'wounded', ctx, roll);
  return pickLine(merchant, 'greeting', ctx, roll);
}
